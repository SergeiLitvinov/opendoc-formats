def test_version_four_directory_slots_are_charged_in_shared_item_budget():
    tree = inspect_container_tree(own_cfbf(version=4)[0])
    snapshot = tree.occurrences[0].snapshot
    slots = dict(snapshot.details)['directory_slots']
    assert slots > len(snapshot.items) and tree.charged_items == slots
    assert inspect_container_tree(own_cfbf(version=4)[0], limits=AnatomyLimits(max_items=slots)) == tree
    with pytest.raises(ResourceLimitError):
        inspect_container_tree(own_cfbf(version=4)[0], limits=AnatomyLimits(max_items=slots - 1))


def test_cancellation_during_publication_rolls_back_created_directories(tmp_path, monkeypatch):
    import tools.container_anatomy as implementation
    tree = inspect_container_tree(zip_bytes([('child', zip_bytes([]))]), capture=True)
    output = tmp_path / 'output'
    event = Event()
    original = implementation.save_dissection
    def stop_after_first(snapshot, target):
        original(snapshot, target)
        event.set()

    monkeypatch.setattr(implementation, 'save_dissection', stop_after_first)
    with pytest.raises(OperationCancelledError):
        with cancellation_scope(event.is_set, 'Own publish'):
            save_tree(tree, output)
    assert not output.exists()
