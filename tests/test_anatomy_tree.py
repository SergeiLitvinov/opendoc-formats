def embedded_cfbf():
    """Patch independent known physical chains, not offsets generated by the inspector."""
    data = bytearray(own_cfbf()[0])
    small = zip_bytes([('small.txt', b'Own small nested bytes')]).ljust(145, b'\x00')
    assert len(small) == 145
    for index, sector in enumerate((0, 2, 1)):
        chunk = small[index * 64:(index + 1) * 64]
        offset = 4 * 512 + sector * 64
        data[offset:offset + len(chunk)] = chunk
    large = zip_bytes([('large.txt', b'Own large nested bytes')]).ljust(4096, b'\x00')
    for index, sector in enumerate((4, 6, 5, 7, 9, 8, 10, 11)):
        data[(sector + 1) * 512:(sector + 2) * 512] = large[index * 512:(index + 1) * 512]
    return bytes(data), small, large


def test_nested_zip_cfbf_mini_and_fat_streams_keep_exact_scoped_bytes():
    compound, small, large = embedded_cfbf()
    source = zip_bytes([('word/embeddings/own.bin', compound), ('unknown.bin', b'Opaque PK\x03\x04 suffix')])
    tree = inspect_container_tree(source, capture=True)
    assert [entry.location for entry in tree.occurrences] == [(), ('zip:/word/embeddings/own.bin',),
        ('zip:/word/embeddings/own.bin', 'cfbf:directory=1'),
        ('zip:/word/embeddings/own.bin', 'cfbf:directory=2')]
    assert [entry.snapshot.container for entry in tree.occurrences] == ['zip', 'cfbf', 'zip', 'zip']
    cfbf = tree.occurrences[1].snapshot
    assert b''.join(item.payload for item in cfbf.items if item.kind == 'cfbf-physical-sector') == compound
    assert next(item for item in cfbf.items if item.locator == 'cfbf:directory=1').payload == small
    assert next(item for item in cfbf.items if item.locator == 'cfbf:directory=2').payload == large
    assert tree.occurrences[2].snapshot.items[0].payload == b'Own small nested bytes'
    assert tree.occurrences[3].snapshot.items[0].payload == b'Own large nested bytes'
    assert not any(item.xml_nodes for entry in tree.occurrences for item in entry.snapshot.items)
    assert json.loads(json.dumps(tree.to_dict()))['assessment_complete'] is False


def test_identical_payloads_are_distinct_occurrences_and_capture_does_not_change_budget():
    child = zip_bytes([('payload', b'Own bytes')])
    source = zip_bytes([('folder/one!.zip', child), ('два.zip', child)])
    captured = inspect_container_tree(source, capture=True)
    opaque = inspect_container_tree(source)
    assert captured.to_dict() == opaque.to_dict()
    assert len(captured.occurrences) == 3
    assert captured.occurrences[1].snapshot.source_sha256 == captured.occurrences[2].snapshot.source_sha256
    assert captured.occurrences[1].location != captured.occurrences[2].location
    assert all(item.payload is None for occurrence in opaque.occurrences for item in occurrence.snapshot.items)


@pytest.mark.parametrize('quota', ['max_items', 'max_total_bytes'])
def test_shared_budget_exact_boundary_and_one_below_across_siblings(quota):
    source = zip_bytes([('first', own_cfbf()[0]), ('second', zip_bytes([('p', b'bytes')]))])
    tree = inspect_container_tree(source)
    bound = tree.charged_items if quota == 'max_items' else tree.charged_bytes
    assert inspect_container_tree(source, limits=replace(AnatomyLimits(), **{quota: bound})).to_dict() == tree.to_dict()
    with pytest.raises(ResourceLimitError, match='max_items|max_total_bytes'):
        inspect_container_tree(source, limits=replace(AnatomyLimits(), **{quota: bound - 1}))
    assert inspect_container_tree(source).to_dict() == tree.to_dict()


def test_empty_zip_occurrences_still_cost_one_item_and_inventory_byte():
    empty = zip_bytes([])
    source = zip_bytes([('empty', empty)])
    tree = inspect_container_tree(source)
    assert len(tree.occurrences) == 2
    assert tree.charged_items == 2
    assert tree.charged_bytes == len(source) + len(empty) * 2 + 1
    assert inspect_container_tree(source, limits=replace(AnatomyLimits(), max_items=2,
                                  max_total_bytes=tree.charged_bytes)).to_dict() == tree.to_dict()


def test_depth_container_count_and_part_size_are_enforced_in_children():
    child = zip_bytes([('p', b'bytes')])
    source = zip_bytes([('child', child)])
