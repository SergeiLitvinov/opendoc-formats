def test_native_import_guards_and_independent_zipfile_crosscheck(monkeypatch):
    original = builtins.__import__
    def guarded(name, *args, **kwargs):
        if name.split('.')[0] in {'olefile', 'docx', 'pptx', 'PIL', 'lxml', 'fontTools', 'fitz', 'pypdf'}:
            raise AssertionError(f'Unnecessary engine: {name}')
        return original(name, *args, **kwargs)

    monkeypatch.setattr(builtins, '__import__', guarded)
    compound, small, large = embedded_cfbf()
    tree = inspect_container_tree(zip_bytes([('own', compound)]), capture=True)
    for payload, entry in zip((small, large), tree.occurrences[2:], strict=True):
        with zipfile.ZipFile(io.BytesIO(payload)) as archive:
            assert archive.testzip() is None
            assert entry.snapshot.items[0].payload == archive.read(archive.namelist()[0])


def test_late_cancellation_in_nested_reader_is_atomic_and_scope_recovers(tmp_path, monkeypatch):
    import opendoc_formats.anatomy_tree as implementation
    source = zip_bytes([('child', own_cfbf()[0])])
    path = tmp_path / 'own.zip'
    path.write_bytes(source)
    event = Event()
    original = implementation.inspect_binary
    def stop_after_child(data, **kwargs):
        snapshot = original(data, **kwargs)
        if snapshot.container == 'cfbf':
            event.set()
        return snapshot

    with monkeypatch.context() as context:
        context.setattr(implementation, 'inspect_binary', stop_after_child)
        with pytest.raises(OperationCancelledError):
            inspect_container_tree(path, cancelled=event.is_set)
    assert path.read_bytes() == source
    assert len(inspect_container_tree(path).occurrences) == 2


def test_comparison_separates_nested_changes_and_new_occurrences():
    before = inspect_container_tree(zip_bytes([('child', zip_bytes([('p', b'Before')]))]))
    after = inspect_container_tree(zip_bytes([('child', zip_bytes([('p', b'After')])), ('new', zip_bytes([]))]))
    comparison = compare_container_trees(before, after)
    assert comparison['added'] == [['zip:/new']] and comparison['removed'] == []
    child = next(entry for entry in comparison['shared'] if entry['location'] == ['zip:/child'])
    assert child['comparison']['content_changed'] == ['zip:/p']
    assert comparison['assessment_complete'] is False
    replaced = inspect_container_tree(zip_bytes([('child', own_cfbf()[0])]))
    profiles = compare_container_trees(before, replaced)
    assert profiles['profile_changed'] == [{'location': ['zip:/child'], 'before': 'zip', 'after': 'cfbf'}]
    assert len(profiles['shared']) == 1


def test_cli_generated_directories_payloads_and_comparison(tmp_path, monkeypatch):
    compound, _, _ = embedded_cfbf()
    source, output = tmp_path / 'own.zip', tmp_path / 'output'
    source.write_bytes(zip_bytes([('word/embeddings/own.bin', compound)]))
    monkeypatch.setattr(sys, 'argv', ['container_anatomy', str(source), '--output', str(output), '--compare', str(source)])
    main()
    report = json.loads((output / 'inventory.json').read_text(encoding='utf-8'))
    assert len(report['containers']) == 4
    for record in report['containers']:
        inventory = output / record['inventory_file']
        assert inventory.parent.parent == output
        payload = json.loads(inventory.read_text(encoding='utf-8'))
        for item in payload['items']:
            assert (inventory.parent / item['payload_file']).stat().st_size == item['size']
    before = (output / 'inventory.json').read_bytes()
    with pytest.raises(FileExistsError):
        main()
    assert (output / 'inventory.json').read_bytes() == before


def test_publication_failure_rolls_back_only_owned_files(tmp_path, monkeypatch):
    import tools.container_anatomy as implementation
    tree = inspect_container_tree(zip_bytes([('child', zip_bytes([]))]), capture=True)
    output = tmp_path / 'output'
    sentinel = tmp_path / 'sentinel'
    sentinel.write_bytes(b'Keep')
    original = implementation.save_dissection
    def fail_second(snapshot, target):
        if target.name == 'container-000001':
            raise OSError('Own simulated publication error')
        return original(snapshot, target)

    monkeypatch.setattr(implementation, 'save_dissection', fail_second)
    with pytest.raises(OSError, match='simulated publication'):
        save_tree(tree, output)
    assert not output.exists() and sentinel.read_bytes() == b'Keep'


