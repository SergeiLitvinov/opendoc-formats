def test_nested_compression_ratio_and_input_bytes_are_not_reset():
    child = zip_bytes([('expanded', b'A' * 5000)])
    source = zip_bytes([('child', child)], compression=zipfile.ZIP_STORED)
    with pytest.raises(ResourceLimitError, match='zip:/child'):
        inspect_container_tree(source, limits=AnatomyLimits(max_ratio=10))
    # The compressed outer file fits; the complete logical child exceeds input quota.
    child = zip_bytes([('expanded', b'A' * 5000)], compression=zipfile.ZIP_STORED)
    source = zip_bytes([('child', child)])
    assert len(source) < len(child)
    with pytest.raises(ResourceLimitError, match='zip:/child.*Input exceeds'):
        inspect_container_tree(source, limits=AnatomyLimits(max_input_bytes=len(child) - 1))


